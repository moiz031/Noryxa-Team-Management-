-- Activity events table
create table if not exists storage_events (
  id bigint generated by default as identity primary key,
  type text not null,
  entity_id uuid not null,
  bucket text not null,
  file_path text not null,
  performed_by uuid not null references auth.users(id),
  created_at timestamp with time zone default now()
);

-- Function to log events
create function public.log_storage_event(p_bucket text, p_path text, p_type text, p_entity_id uuid, p_user_id uuid) returns void language plpgsql as $$
begin
  insert into storage_events (type, entity_id, bucket, file_path, performed_by) values (p_type, p_entity_id, p_bucket, p_path, p_user_id);
end;
$$;
